print("--- Програма для обчислення прямокутника ---")

# Введення даних з клавіатури
a = float(input("Введіть довжину сторони A: "))
b = float(input("Введіть довжину сторони B: "))

# Обчислення
периметр = 2 * (a + b)
площа = a * b

# Виведення результату
print(f"Периметр прямокутника: {периметр}")
print(f"Площа прямокутника: {площа}")